// Deterministic string hash (djb2-ish) so the same question always maps to
// the same quote within a render, but different question text/position
// lands on a different one - no need for extra component state.
export function pickSupportiveQuote(seed) {
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = (hash * 31 + seed.charCodeAt(i)) >>> 0;
  }
  return SUPPORTIVE_QUOTES[hash % SUPPORTIVE_QUOTES.length];
}
